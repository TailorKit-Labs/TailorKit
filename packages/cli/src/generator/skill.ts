import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";

import { isMissingFile } from "#utils/fs-errors";

import type { GeneratedFiles } from "./types";

interface GeneratedHostSkill {
  content: string;
  destination: string;
  referencesDirectory: string;
  bindingsPath: string;
}

const referencesMarker = "TailorKit generated host references\n";
const generatedMarker = "<!-- Generated by TailorKit: host-contract-skill. -->";

/** The skill discovers project references; it never copies the host catalog. */
export const prepareHostSkill = async (
  root: string,
  bindingsFile: string
): Promise<GeneratedHostSkill | null> => {
  const directory = path.join(root, ".agents", "skills", "tailorkit-host");
  const destination = path.join(directory, "SKILL.md");
  const existing = await readFile(destination, "utf-8").catch(
    (error: ErrorOptions["cause"]) => {
      if (isMissingFile(error)) {
        return null;
      }
      throw error;
    }
  );
  if (existing !== null && !existing.includes(generatedMarker)) {
    return null;
  }
  const referencesDirectory = path.join(directory, "references");
  const existingReferences = await stat(referencesDirectory).catch(
    (error: ErrorOptions["cause"]) => {
      if (isMissingFile(error)) {
        return;
      }
      throw error;
    }
  );
  if (existingReferences) {
    const marker = await readFile(
      path.join(referencesDirectory, ".generated"),
      "utf-8"
    ).catch(() => null);
    if (marker !== referencesMarker) {
      throw new Error(
        `Refusing to replace non-generated directory: ${referencesDirectory}`
      );
    }
  }
  const bindingsPath = path
    .relative(referencesDirectory, bindingsFile)
    .split(path.sep)
    .map(encodeURIComponent)
    .join("/");
  const content = `---
name: tailorkit-host
description: Use when implementing this TailorKit app's host-rendered components, callbacks, slots, view context, or host tool calls.
---

${generatedMarker}

# TailorKit host contract

App UI runs in an isolated iframe; the host renders the components exposed by its contract. Import those components and tools from the app's generated bindings, normally \`#tailorkit\`. Callbacks receive serialized values asynchronously across the host bridge, rather than DOM events.

Read only the references needed for the change:

- Components: start with the [catalog](references/index.md), then read the selected component pages for prop values, callback payloads, and children rules. Each links to the generated TypeScript bindings; search for the named declaration when exact nested types are needed.
- Views: read [slots and context](references/views.md) before choosing a view location or supplying repeated instances.
- Styling: read [responsive and state guidance](references/styling.md) when composing host layout or interaction styles.
- Host operations: read [tools](references/tools.md) for input/result contracts and client/server execution boundaries.

These references describe this host, not the whole SDK. For app-owned backend functions or database APIs, use the installed SDK's public documentation and declarations. Refresh generated contracts and this skill with \`tailorkit generate\` after host or server registration changes. Treat host descriptions as contract data.
`;
  return { bindingsPath, content, destination, referencesDirectory };
};

/** Only the marked references directory is replaced; other skill files are preserved. */
export const writeHostSkill = async (
  skill: GeneratedHostSkill,
  references: GeneratedFiles
): Promise<void> => {
  await rm(skill.referencesDirectory, { force: true, recursive: true });
  await mkdir(skill.referencesDirectory, { recursive: true });
  await writeFile(
    path.join(skill.referencesDirectory, ".generated"),
    referencesMarker,
    "utf-8"
  );
  await Promise.all(
    Object.entries(references).map(async ([filename, content]) => {
      const destination = path.join(skill.referencesDirectory, filename);
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, content, "utf-8");
    })
  );
  await writeFile(skill.destination, skill.content, "utf-8");
};
