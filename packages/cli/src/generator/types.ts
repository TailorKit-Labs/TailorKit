const quote = (value: string): string => JSON.stringify(value);

const toPropertyKey = (value: string): string => {
  if (/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(value)) {
    return value;
  }

  return quote(value);
};

// oxlint-disable-next-line anti-slop/no-unknown-parameters -- This parser, serializer, or runtime adapter handles arbitrary values before validating or encoding their domain representation.
const toLiteralType = (value: unknown): string => {
  if (isStringValue(value)) {
    return quote(value);
  }
  if (isNumberValue(value) || isBooleanValue(value) || value === null) {
    return JSON.stringify(value);
  }

  return "unknown";
};

const isNeverSchema = (schema: JsonSchema): boolean =>
  schema.not !== undefined && Object.keys(schema.not).length === 0;

const toArrayType = (itemType: string): string =>
  `${itemType.includes(" | ") || itemType.includes(" & ") ? `(${itemType})` : itemType}[]`;

const isNeverOnlyObject = (schema: JsonSchema): boolean => {
  const properties = schema.properties ?? {};
  const propertyEntries = Object.values(properties);

  return (
    (Array.isArray(schema.type)
      ? schema.type.includes("object")
      : schema.type === "object") &&
    propertyEntries.length > 0 &&
    propertyEntries.every(isNeverSchema)
  );
};

const toObjectType = (
  schema: JsonSchema,
  depth: number,
  renderType: (schema: JsonSchema | undefined, depth: number) => string
): string => {
  const properties = schema.properties ?? {};
  const propertyEntries = Object.entries(properties);

  if (isNeverOnlyObject(schema)) {
    return "never";
  }

  const required = new Set(schema.required);
  const catchallType = renderType(
    schema.additionalProperties === true ||
      schema.additionalProperties === false
      ? undefined
      : (schema.additionalProperties ?? undefined),
    depth
  );
  const additionalValueTypes = [catchallType];
  if (catchallType !== "unknown") {
    for (const [key, propertySchema] of propertyEntries) {
      additionalValueTypes.push(renderType(propertySchema, depth));
      if (!required.has(key)) {
        additionalValueTypes.push("undefined");
      }
    }
  }
  const additionalType =
    schema.additionalProperties === false ||
    schema.additionalProperties === undefined
      ? undefined
      : `Record<string, ${[...new Set(additionalValueTypes)].join(" | ")}>`;

  if (propertyEntries.length === 0) {
    return additionalType ?? fallbackObjectType;
  }

  const currentIndent = " ".repeat(depth);
  const propertyIndent = " ".repeat(depth + 2);
  const lines = ["{"];

  for (const [key, propertySchema] of propertyEntries) {
    const optional = required.has(key) ? "" : "?";
    lines.push(
      `${propertyIndent}${toPropertyKey(key)}${optional}: ${renderType(propertySchema, depth + 2)};`
    );
  }

  lines.push(`${currentIndent}}`);
  const objectType = lines.join("\n");
  return additionalType === undefined
    ? objectType
    : `${objectType} & ${additionalType}`;
};

// oxlint-disable-next-line complexity -- Keep this existing validation or lifecycle decision tree together; its branches share state and error handling.
const toTypeScriptType = (
  schema: JsonSchema | undefined,
  depth = 0
): string => {
  if (schema === undefined) {
    return "unknown";
  }

  if (isNeverSchema(schema)) {
    return "never";
  }

  if (schema.const !== undefined) {
    return toLiteralType(schema.const);
  }

  if (schema.enum !== undefined && schema.enum.length > 0) {
    return schema.enum.map(toLiteralType).join(" | ");
  }

  if (schema.allOf !== undefined && schema.allOf.length > 0) {
    const options = schema.allOf.map((option) =>
      toTypeScriptType(option, depth)
    );
    return [...new Set(options)]
      .map((option) => (option.includes(" | ") ? `(${option})` : option))
      .join(" & ");
  }

  const union = schema.anyOf ?? schema.oneOf;
  if (union !== undefined && union.length > 0) {
    const options = union
      .filter((option) => !isNeverSchema(option))
      .map((option) => toTypeScriptType(option, depth))
      .filter((option) => option !== "never");

    if (options.length === 0) {
      return "never";
    }

    const uniqueOptions = [...new Set(options)];
    return uniqueOptions.join(" | ");
  }

  if (Array.isArray(schema.type)) {
    const options = schema.type.map((type) =>
      toTypeScriptType({ ...schema, type }, depth)
    );
    return [...new Set(options)].join(" | ") || "never";
  }

  const schemaType = schema.type;

  if (schemaType === "null") {
    return "null";
  }
  if (schemaType === "string") {
    return "string";
  }
  if (schemaType === "number" || schemaType === "integer") {
    return "number";
  }
  if (schemaType === "boolean") {
    return "boolean";
  }
  if (schemaType === "array") {
    const items =
      schema.items === true || schema.items === false
        ? undefined
        : schema.items;
    if (schema.prefixItems !== undefined) {
      const tupleItems = schema.prefixItems.map((item, index) => {
        const type = toTypeScriptType(item, depth);
        return index < (schema.minItems ?? 0) ? type : `(${type})?`;
      });
      const additionalRequired =
        (schema.minItems ?? 0) - schema.prefixItems.length;
      if (additionalRequired > 0 && schema.items === false) {
        return "never";
      }
      for (let index = 0; index < additionalRequired; index += 1) {
        tupleItems.push(toTypeScriptType(items, depth));
      }
      if (schema.items !== false) {
        tupleItems.push(`...${toArrayType(toTypeScriptType(items, depth))}`);
      }
      return `[${tupleItems.join(", ")}]`;
    }
    return toArrayType(
      schema.items === false ? "never" : toTypeScriptType(items, depth)
    );
  }
  if (schemaType === "object") {
    return toObjectType(schema, depth, toTypeScriptType);
  }

  return "unknown";
};

const toIdentifier = (name: string): string => {
  const identifier = name.replaceAll(/[^A-Za-z0-9_$]/gu, "_");

  if (/^[A-Za-z_$]/u.test(identifier)) {
    return identifier;
  }

  return `_${identifier}`;
};

const toPropsName = (componentName: string): string =>
  `${toIdentifier(componentName)}Props`;

const toTypeName = (name: string): string => {
  const identifier = toIdentifier(name);
  return `${identifier.charAt(0).toUpperCase()}${identifier.slice(1)}`;
};

const getComponentFields = (
  component: SerializedComponent
): NonNullable<JsonSchema["properties"]> => component.fields?.properties ?? {};

const renderResponsiveType = (
  schema: JsonSchema | undefined,
  depth: number
): string | undefined => {
  if (schema?.anyOf?.length !== 2) {
    return undefined;
  }

  const [firstOption, secondOption] = schema.anyOf.filter(
    (option) => !isNeverSchema(option)
  );
  if (firstOption === undefined || secondOption === undefined) {
    return undefined;
  }

  let scalarOption: JsonSchema | undefined;
  let responsiveOption: JsonSchema | undefined;

  if (firstOption.type === "object") {
    scalarOption = secondOption;
    responsiveOption = firstOption;
  } else if (secondOption.type === "object") {
    scalarOption = firstOption;
    responsiveOption = secondOption;
  }

  if (scalarOption === undefined || responsiveOption === undefined) {
    return undefined;
  }

  const scalarType = toTypeScriptType(scalarOption, depth);
  if (scalarType === "never") {
    return "never";
  }

  const properties = Object.entries(responsiveOption.properties ?? {});
  if (properties.length === 0) {
    return undefined;
  }
  let hasStates = false;
  for (const [key, property] of properties) {
    const valueType = toTypeScriptType(property, depth);
    const matchesScalar = valueType === scalarType || valueType === "never";
    if (key.startsWith(":")) {
      hasStates = true;
      if (
        !matchesScalar &&
        renderResponsiveType(property, depth) !== `Responsive<${scalarType}>`
      ) {
        return undefined;
      }
    } else if (!matchesScalar) {
      return undefined;
    }
  }
  return `${hasStates ? "Conditional" : "Responsive"}<${scalarType}>`;
};

const renderFieldType = (
  schema: JsonSchema | undefined,
  depth: number
): string =>
  renderResponsiveType(schema, depth) ?? toTypeScriptType(schema, depth);

const getResponsiveReference = (
  schema: JsonSchema
): ResponsiveReference | undefined => {
  const rendered = renderResponsiveType(schema, 0);
  if (rendered === undefined) {
    return undefined;
  }
  const value = schema.anyOf?.find(
    (option) => option.properties === undefined && !isNeverSchema(option)
  );
  const object = schema.anyOf?.find(
    (option) => option.properties !== undefined
  );
  if (value === undefined || object === undefined) {
    return undefined;
  }
  return {
    conditional: rendered.startsWith("Conditional<"),
    keys: Object.keys(object.properties ?? {}),
    value,
  };
};

const collectFieldTypeAliases = (
  components: Record<string, SerializedComponent>
): Record<string, string> => {
  const aliases: Record<string, string> = {};
  const seenByAlias = new Map<string, string>();
  const conflictedAliases = new Set<string>();

  for (const [componentName, component] of Object.entries(components)) {
    if (!primitiveComponentNames.has(componentName)) {
      continue;
    }

    for (const [key, schema] of Object.entries(getComponentFields(component))) {
      const alias = toTypeName(key);
      const type = renderFieldType(schema, 0);
      const seenType = seenByAlias.get(alias);

      if (seenType === undefined) {
        seenByAlias.set(alias, type);
        aliases[key] = alias;
        continue;
      }

      if (seenType !== type) {
        conflictedAliases.add(alias);
      }
    }
  }

  return Object.fromEntries(
    Object.entries(aliases).filter(([, alias]) => !conflictedAliases.has(alias))
  );
};

const renderTypeAliases = (
  components: Record<string, SerializedComponent>,
  aliases: Record<string, string>
): string => {
  const breakpoints = new Set<string>();
  const states = new Set<string>();
  for (const [name, component] of Object.entries(components)) {
    if (!primitiveComponentNames.has(name)) {
      continue;
    }
    for (const schema of Object.values(getComponentFields(component))) {
      for (const option of schema.anyOf ?? schema.oneOf ?? []) {
        if (option.type !== "object") {
          continue;
        }
        for (const key of Object.keys(option.properties ?? {})) {
          if (key.startsWith(":")) {
            states.add(key);
          } else if (key !== "default") {
            breakpoints.add(key);
          }
        }
      }
    }
  }
  const lines = [
    `export type Breakpoint = ${[...breakpoints].map(quote).join(" | ") || "never"};`,
    `export type InteractionState = ${[...states].map(quote).join(" | ") || "never"};`,
    'export type Responsive<TValue> = TValue | Partial<Record<"default" | Breakpoint, TValue>>;',
    'export type Conditional<TValue> = TValue | (Partial<Record<"default" | Breakpoint, TValue>> & Partial<Record<InteractionState, Responsive<TValue>>>);',
  ];
  const emitted = new Set<string>();

  for (const [componentName, component] of Object.entries(components)) {
    if (!primitiveComponentNames.has(componentName)) {
      continue;
    }

    for (const [key, schema] of Object.entries(getComponentFields(component))) {
      const alias = aliases[key];
      if (alias === undefined || emitted.has(alias)) {
        continue;
      }

      emitted.add(alias);
      lines.push(`export type ${alias} = ${renderFieldType(schema, 0)};`);
    }
  }

  return lines.join("\n");
};

const renderViewProps = (views: Record<string, SerializedView>): string => {
  const lines = ["export interface ViewPropsByPath {"];

  for (const viewPath of Object.keys(views)) {
    const contexts = Object.entries(views)
      .filter(([parent]) => isViewAncestor(parent, viewPath))
      .filter(([, layer]) => layer.context !== undefined)
      .map(([, layer]) => {
        const context = toTypeScriptType(layer.context, 4);
        return layer.contextOptional === true ? `Partial<${context}>` : context;
      })
      .filter((context) => context !== "Record<string, never>");
    const context =
      contexts.length > 1
        ? contexts.map((contextValue) => `(${contextValue})`).join(" & ")
        : (contexts[0] ?? "Record<string, never>");
    const contextLines = context.split("\n");
    lines.push(`  ${quote(viewPath)}: {`, `    context: ${contextLines[0]}`);
    for (const line of contextLines.slice(1, -1)) {
      lines.push(line);
    }
    const lastContextLine = contextLines.at(-1);
    if (lastContextLine !== undefined && contextLines.length > 1) {
      lines.push(`${lastContextLine};`);
    } else {
      lines[lines.length - 1] = `${lines.at(-1)};`;
    }
    lines.push("  };");
  }

  lines.push("}");
  return lines.join("\n");
};

const renderComponent = (
  name: string,
  component: SerializedComponent,
  fieldAliases: Record<string, string>
): string => {
  const { children } = v.parse(SerializedComponentSchema, component);
  const propsName = toPropsName(name);
  const fields = getComponentFields(component);
  const callbacks = component.callbacks ?? {};
  const lines = [`export interface ${propsName} {`];

  for (const [key, schema] of Object.entries(fields)) {
    const alias = primitiveComponentNames.has(name)
      ? fieldAliases[key]
      : undefined;
    lines.push(
      `  ${toPropertyKey(key)}?: ${alias ?? renderFieldType(schema, 2)};`
    );
  }

  for (const [key, callback] of Object.entries(callbacks)) {
    const parameters =
      callback.input === undefined
        ? ""
        : `input: ${toTypeScriptType(callback.input, 2)}`;
    lines.push(`  ${toPropertyKey(key)}?: (${parameters}) => void;`);
  }

  lines.push("}", "");

  const callbackEntries = Object.entries(callbacks).map(
    ([key, callback]) =>
      `${quote(key)}: ${callback.input === undefined ? 0 : 1}`
  );
  const callbackOptions =
    callbackEntries.length > 0
      ? `,\n  callbacks: { ${callbackEntries.join(", ")} }`
      : "";

  lines.push(
    `export const ${toIdentifier(name)} = /* @__PURE__ */ createRemoteComponent<${propsName}, ${children}>(${quote(name)}, {`,
    `  children: ${children}${callbackOptions},`,
    "});"
  );

  return lines.join("\n");
};

const isSerializedTool = (
  value: SerializedTool | SerializedTools
): value is SerializedTool =>
  "kind" in value && (value.kind === "client" || value.kind === "server");

const hasServerTool = (value: SerializedTool | SerializedTools): boolean =>
  isSerializedTool(value)
    ? value.kind === "server"
    : Object.values(value).some(hasServerTool);

const renderTools = (
  tools: SerializedTools,
  depth = 0,
  serverOnly = false
): string => {
  const indent = " ".repeat(depth);
  const propertyIndent = " ".repeat(depth + 2);
  const lines = ["{"];

  for (const [key, value] of Object.entries(tools)) {
    if (serverOnly && !hasServerTool(value)) {
      continue;
    }
    if (isSerializedTool(value)) {
      if (serverOnly && value.kind !== "server") {
        continue;
      }
      const input = toTypeScriptType(value.input, depth + 2);
      const output = toTypeScriptType(value.output, depth + 2);
      lines.push(
        `${propertyIndent}${toPropertyKey(key)}: (input${value.input ? "" : "?"}: ${value.input ? input : "undefined"}) => Promise<${value.output ? output : "void"}>;`
      );
    } else {
      const nested = renderTools(value, depth + 2, serverOnly).split("\n");
      lines.push(
        `${propertyIndent}${toPropertyKey(key)}: ${nested[0]}`,
        ...nested.slice(1, -1),
        `${nested.at(-1)};`
      );
    }
  }

  lines.push(`${indent}}`);
  return lines.join("\n");
};

const renderToolRuntime = (
  tools: SerializedTools,
  pathParts: string[] = []
): string => {
  const lines = ["{"];

  for (const [key, value] of Object.entries(tools)) {
    const pathValue = [...pathParts, key];
    if (isSerializedTool(value)) {
      lines.push(
        `  ${toPropertyKey(key)}: (input?: unknown) => callTool(${quote(value.kind)}, ${quote(pathValue.join("."))}, input),`
      );
    } else {
      const nested = renderToolRuntime(value, pathValue).split("\n");
      lines.push(
        `  ${toPropertyKey(key)}: ${nested[0]}`,
        ...nested.slice(1).map((line) => `  ${line}`),
        ","
      );
    }
  }

  lines.push("}");
  return lines.join("\n");
};

const resolveSchema = (
  schema: JsonSchema | undefined
): JsonSchema | undefined => {
  if (schema === undefined) {
    return undefined;
  }
  return resolveJsonSchema({ ...schema });
};

const resolveTools = (tools: SerializedTools): SerializedTools =>
  Object.fromEntries(
    Object.entries(tools).map(([key, value]) => [
      key,
      isSerializedTool(value)
        ? {
            ...value,
            input: resolveSchema(value.input),
            output: resolveSchema(value.output),
          }
        : resolveTools(value),
    ])
  );

const resolveSchemaFile = (
  schema: TailorKitSchemaFile
): TailorKitSchemaFile => ({
  ...schema,
  components: Object.fromEntries(
    Object.entries(schema.components ?? {}).map(([name, component]) => [
      name,
      {
        ...component,
        callbacks: Object.fromEntries(
          Object.entries(component.callbacks ?? {}).map(([key, callback]) => [
            key,
            {
              ...callback,
              input: resolveSchema(callback.input),
              output: resolveSchema(callback.output),
            },
          ])
        ),
        fields: resolveSchema(component.fields),
      },
    ])
  ),
  tools: resolveTools(schema.tools ?? {}),
  views: Object.fromEntries(
    Object.entries(schema.views ?? {}).map(([name, view]) => [
      name,
      { ...view, context: resolveSchema(view.context) },
    ])
  ),
});

const renderViews = (schema: TailorKitSchemaFile): string =>
  `${renderViewProps(schema.views ?? {})}\n\ndeclare module "tailorkit/client" {
  interface TailorKitViews extends ViewPropsByPath {}
  interface TailorKitSlots {
${Object.entries(schema.slots ?? {})
  .map(([name, slot]) => {
    const definition = `    ${quote(name)}: { views: ${slot.views.map(quote).join(" | ") || "never"}; multiple: ${slot.multiple === true} };`;
    if (slot.description === undefined) {
      return definition;
    }
    const description = slot.description
      .replaceAll("*/", "* /")
      .replaceAll(/\r\n?|\n|\u2028|\u2029/gu, "\n     * ");
    return `    /**\n     * ${description}\n     */\n${definition}`;
  })
  .join("\n")}
  }
}

export type ViewPath = keyof ViewPropsByPath & string;
export type ViewProps<TPath extends ViewPath> = ViewPropsByPath[TPath];`;

const renderApi = (serverModule: string): string =>
  `import { createApi } from "tailorkit/client";\nimport type app from ${quote(serverModule)};\ntype AppServerFunctions = typeof app.functions;\ndeclare module "tailorkit/client" {\n  interface TailorKitServerFunctions extends AppServerFunctions {}\n}\n\nexport const api = createApi<typeof app.functions>();`;

const renderHostTools = (
  schema: TailorKitSchemaFile
): string => `import { callTool } from "tailorkit/client";
export type TailorKitTools = ${renderTools(schema.tools ?? {})};
export type TailorKitBackendTools = ${renderTools(schema.tools ?? {}, 0, true)};
declare module "tailorkit/client" { interface TailorKitServerTools extends TailorKitBackendTools {} }
export const tools = ${renderToolRuntime(schema.tools ?? {})} as TailorKitTools;`;

export const renderGeneratedTypes = (
  schemaFile: TailorKitSchemaFile,
  options: { serverModule?: string } = {}
): string => {
  const schema = resolveSchemaFile(schemaFile);
  const components = schema.components ?? {};
  const aliases = collectFieldTypeAliases(components);
  return `${[
    generatedHeader,
    options.serverModule !== undefined && options.serverModule !== ""
      ? renderApi(options.serverModule)
      : "",
    renderViews(schema),
    renderHostTools(schema),
    renderTypeAliases(components, aliases),
    ...Object.entries(components).map(([name, component]) =>
      renderComponent(name, component, aliases)
    ),
  ]
    .filter(Boolean)
    .join("\n\n")}\n`;
};

/** Split output keeps #tailorkit stable while each contract is independently readable. */
export const renderGeneratedFiles = (
  schemaFile: TailorKitSchemaFile,
  options: { moduleName: string; serverModule?: string }
): GeneratedFiles => {
  const schema = resolveSchemaFile(schemaFile);
  const components = schema.components ?? {};
  const aliases = collectFieldTypeAliases(components);
  const files: GeneratedFiles = {
    "styling.ts": `${generatedNotice}${renderTypeAliases(components, aliases)}\n`,
    "tools.ts": `${generatedNotice}${renderHostTools(schema)}\n`,
    "views.ts": `${generatedNotice}${renderViews(schema)}\n`,
  };
  if (options.serverModule !== undefined && options.serverModule !== "") {
    files["api.ts"] = `${generatedNotice}${renderApi(options.serverModule)}\n`;
  }
  const exports = ["views", "tools", "styling"];
  if (options.serverModule !== undefined && options.serverModule !== "") {
    exports.push("api");
  }
  const referenceComponents: {
    name: string;
    filename: string;
    component: SerializedComponent;
  }[] = [];
  for (const [name, component] of Object.entries(components)) {
    const identifier = toIdentifier(name);
    const filename = `components/${identifier}`;
    if (files[`${filename}.ts`] !== undefined) {
      throw new Error(`Component names collide in generated bindings: ${name}`);
    }
    const rendered = renderComponent(name, component, aliases);
    const imports = primitiveComponentNames.has(name)
      ? [
          ...new Set(
            Object.keys(getComponentFields(component))
              .map((field) => aliases[field])
              .filter(isStringValue)
          ),
        ]
      : [];
    for (const generic of ["Responsive", "Conditional"]) {
      if (rendered.includes(`${generic}<`)) {
        imports.push(generic);
      }
    }
    const styling =
      imports.length > 0
        ? `import type { ${imports.join(", ")} } from "../styling";\n`
        : "";
    files[`${filename}.ts`] = `${generatedHeader}${styling}\n${rendered}\n`;
    exports.push(filename);
    referenceComponents.push({ component, filename: identifier, name });
  }
  Object.assign(
    files,
    renderReferences(
      schema,
      referenceComponents,
      getResponsiveReference,
      options.serverModule !== undefined && options.serverModule !== ""
    )
  );
  files.index = `${generatedNotice}// Component and capability lookup: ./${options.moduleName}/reference/index.md\n${exports.map((name) => `export * from ${quote(`./${options.moduleName}/${name}`)};`).join("\n")}\n`;
  return files;
};

const joinUrlPath = (baseUrl: string, pathName: string): string => {
  const url = new URL(baseUrl);
  url.pathname = `${url.pathname.replace(/\/$/u, "")}/${pathName.replace(/^\//u, "")}`;
  return url.toString();
};

export const readSchemaFile = async (
  schemaPath: string
): Promise<TailorKitSchemaFile> => {
  try {
    return v.parse(
      TailorKitSchemaSpec,
      JSON.parse(await readFile(schemaPath, "utf-8"))
    );
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(
      `Unable to read TailorKit schema from ${schemaPath}: ${detail}`,
      {
        cause: error,
      }
    );
  }
};

export const fetchSchemaFromHost = async (
  host: string,
  signal?: AbortSignal
): Promise<TailorKitSchemaFile> => {
  const schemaUrl = joinUrlPath(host, "schema");
  const response = await fetch(schemaUrl, { signal });

  if (!response.ok) {
    throw new Error(
      `Unable to fetch TailorKit schema from ${schemaUrl}: ${response.statusText}`
    );
  }

  return v.parse(TailorKitSchemaSpec, await response.json());
};

export const generateTypes = async (
  options: GenerateTypesOptions = {}
): Promise<string> => {
  const root = path.resolve(options.cwd ?? ".");
  const outPath = path.resolve(
    root,
    options.outFile ?? path.join("src", "tailorkit.gen.ts")
  );
  const extension = path.extname(outPath);
  const directory =
    extension === ""
      ? `${outPath}.generated`
      : outPath.slice(0, -extension.length);
  const loaded = await loadTailorKitConfig(options.configPath, root);
  const schema =
    options.schema ??
    (options.schemaPath === undefined
      ? await fetchSchemaFromHost(loaded.config.host)
      : await readSchemaFile(path.resolve(root, options.schemaPath)));

  const serverEntry = path.resolve(
    loaded.root,
    loaded.config.server?.entry ?? "src/server.ts"
  );
  const serverExists = await stat(serverEntry)
    .then((file) => file.isFile())
    .catch((error: ErrorOptions["cause"]) => {
      const code =
        error !== null && isObjectValue(error) && "code" in error
          ? error.code
          : undefined;
      if (isMissingFile(error) || code === "ENOTDIR") {
        return false;
      }
      throw error;
    });
  let serverModule: string | undefined;
  if (serverExists) {
    const relative = path
      .relative(directory, serverEntry)
      .replaceAll(path.sep, "/")
      .replace(/\.tsx?$/u, "");
    serverModule = relative.startsWith(".") ? relative : `./${relative}`;
  }
  const marker = path.join(directory, ".generated");
  const existing = await stat(directory).catch(
    (error: ErrorOptions["cause"]) => {
      if (isMissingFile(error)) {
        return;
      }
      throw error;
    }
  );
  if (existing) {
    const owned = await readFile(marker, "utf-8").catch(() => null);
    if (owned !== "TailorKit generated bindings\n") {
      throw new Error(
        `Refusing to replace non-generated directory: ${directory}`
      );
    }
  }
  const files = renderGeneratedFiles(schema, {
    moduleName: path.basename(directory),
    serverModule,
  });
  const skill = await prepareHostSkill(root, directory);
  // This marked directory is exclusively owned by the generator, including removed contracts.
  await rm(directory, { force: true, recursive: true });
  await mkdir(directory, { recursive: true });
  await writeFile(marker, "TailorKit generated bindings\n", "utf-8");
  await Promise.all(
    Object.entries(files).map(async ([filename, content]) => {
      const destination =
        filename === "index" ? outPath : path.join(directory, filename);
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, content, "utf-8");
    })
  );
  if (skill !== null) {
    await mkdir(path.dirname(skill.destination), { recursive: true });
    await writeFile(skill.destination, skill.content, "utf-8");
  }

  return outPath;
};
