import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { format } from "oxfmt";
import formatting from "ultracite/oxfmt";

const root = new URL("../", import.meta.url);
const check = process.argv.includes("--check");
const { printWidth, proseWrap, trailingComma } = formatting;
/** @type {Record<string, Array<[string, string, string, string | null]>>} */
const snippets = {
  "app-ui": [
    [
      "Instance resolvers",
      "packages/app/src/views.ts",
      "export interface ViewInstance<",
      "export type SlotName",
    ],
    [
      "Returned view",
      "packages/app/src/views.ts",
      "export interface ViewDefinition<",
      "export type SlotView",
    ],
    [
      "View definition overloads",
      "packages/app/src/views.ts",
      "export function defineView<",
      "export function defineView<\n  TPath extends",
    ],
  ],
  components: [
    [
      "Component definitions",
      "packages/core/src/schema/components.ts",
      "type EmptyCallbackMap",
      "type AnyComponentDefinition",
    ],
    [
      "Callback definitions",
      "packages/core/src/schema/callbacks.ts",
      "export interface CallbackDefinition",
      null,
    ],
  ],
  slots: [
    [
      "Slot definitions",
      "packages/core/src/schema/views.ts",
      "export type SlotDefinitions",
      null,
    ],
    [
      "Instance entries",
      "packages/app/src/views.ts",
      "export interface ViewInstance<",
      "export interface InstanceResolverContext",
    ],
  ],
  tools: [
    [
      "Tool declarations",
      "packages/core/src/schema/tools.ts",
      "export type ToolKind",
      "const build =",
    ],
    [
      "Handler context",
      "packages/core/src/schema/tools.ts",
      "export interface ToolIdentity",
      "export interface ToolImplementationTree",
    ],
    [
      "Tool implementations",
      "packages/core/src/schema/tools.ts",
      "export interface ToolImplementationTree",
      "export interface ToolCallerTree",
    ],
  ],
  views: [
    [
      "Context definitions",
      "packages/core/src/schema/views.ts",
      "export type ContextDefinitions",
      "export interface ResolvedViewMetadata",
    ],
    [
      "Context state",
      "packages/client-core/src/store/local/view-context-types.ts",
      "export interface ViewContextState",
      "export type ViewOptions",
    ],
    [
      "Registration hook",
      "packages/react/src/hooks/use-view-context.ts",
      "export type UseViewContext",
      "export const useViewContext",
    ],
  ],
};

const results = await Promise.all(
  Object.entries(snippets).map(async ([name, sections]) => {
    const blocks = await Promise.all(
      sections.map(async ([title, source, startMarker, endMarker]) => {
        const code = await readFile(new URL(source, root), "utf-8");
        const start = code.indexOf(startMarker);
        const end =
          endMarker === null
            ? code.length
            : code.indexOf(endMarker, start + startMarker.length);
        if (start === -1 || end === -1) {
          throw new Error(
            `Cannot extract ${title} from ${source}; update the reference markers.`
          );
        }
        return (
          `{/* Source: ${source} */}\n<Accordion title="${title}">\n\n` +
          `\`\`\`ts\n${code.slice(start, end).trim()}\n\`\`\`\n\n</Accordion>`
        );
      })
    );
    const output = new URL(`docs/snippets/sdk/${name}.mdx`, root);
    const formatted = await format(
      fileURLToPath(output),
      `{/* Generated by scripts/generate-docs-reference.mjs. Do not edit directly. */}

These type declarations are generated from the SDK source. \`Schema\` denotes a Standard Schema validator.

<AccordionGroup>
${blocks.join("\n\n")}
</AccordionGroup>
`,
      { printWidth, proseWrap, trailingComma }
    );
    if (formatted.errors.length > 0) {
      throw new Error(
        `Cannot format SDK reference ${name}: ${JSON.stringify(formatted.errors)}`
      );
    }
    const content = formatted.code;
    if (check) {
      let existing;
      try {
        existing = await readFile(output, "utf-8");
      } catch (error) {
        if (
          error instanceof Error &&
          "code" in error &&
          error.code === "ENOENT"
        ) {
          existing = null;
        } else {
          throw error;
        }
      }
      if (existing !== content) {
        console.error(`Outdated SDK reference: ${fileURLToPath(output)}`);
        return true;
      }
    } else {
      await mkdir(new URL("./", output), { recursive: true });
      await writeFile(output, content);
    }
    return false;
  })
);
if (results.some(Boolean)) {
  process.exitCode = 1;
} else {
  console.log(
    check ? "SDK references are up to date." : "Generated SDK references."
  );
}
